// build-data.mjs — regenerate app/data/trophies.js from app/data/trophies.json.
// The app loads its data with a static `import` of trophies.js (never fetch()), so the JSON
// is the single source of truth and this script keeps the ES module in lockstep with it.
//
//   node tools/build-data.mjs
//
// Node 22, standard library only.

import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const jsonPath = join(root, 'app', 'data', 'trophies.json');
const jsPath = join(root, 'app', 'data', 'trophies.js');

const doc = JSON.parse(readFileSync(jsonPath, 'utf8'));
const trophies = doc.trophies;
const stages = doc.stages;

if (!Array.isArray(trophies) || trophies.length !== 55) {
  throw new Error(`trophies.json must hold a trophies array of 55 items (got ${trophies?.length ?? 'none'})`);
}

const header = [
  '// Generated by `node tools/build-data.mjs` from app/data/trophies.json — edit the JSON, then regenerate.',
  '// Loaded as a static import so the app never fetches the JSON at run time (offline-first).',
  'export const GAME = "Grand Theft Auto VI";',
  'export const PLATFORM = "PlayStation 5";',
  `export const LIST = ${JSON.stringify(doc.list)};`,
  `export const STAGES = ${JSON.stringify(stages)};`,
  `export const TROPHIES = ${JSON.stringify(trophies)};`,
  '',
].join('\n');

writeFileSync(jsPath, header, 'utf8');
const jsonBytes = statSync(jsonPath).size;
const jsBytes = statSync(jsPath).size;
console.log(`wrote app/data/trophies.js (${jsBytes} bytes) from app/data/trophies.json (${jsonBytes} bytes, ${trophies.length} trophies)`);
